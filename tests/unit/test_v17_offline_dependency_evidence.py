def _bound_file(path: Path, *, semantic_sha256: str | None = None) -> dict[str, object]:
    raw = path.read_bytes()
    result: dict[str, object] = {
        "path": str(path),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "size_bytes": len(raw),
    }
    if semantic_sha256 is not None:
        result["semantic_sha256"] = semantic_sha256
    return result


def _native_log_case(
    tmp_path: Path,
    *,
    mutate: Callable[[dict[str, Any]], None] | None = None,
    mutate_framed: Callable[[bytes], bytes] | None = None,
) -> dict[str, Any]:
    bundle = tmp_path / "bundle"
    bundle.mkdir(mode=0o700)
    work = tmp_path / "work"
    work.mkdir(mode=0o700)
    target_venv = work / "native_venv"
    session_path = bundle / "00_session.json"
    session_payload = {"version": "myquant.v17.v2.phase0-session.v2", "session_id": "s1"}
    session_path.write_bytes(subject._canonical_bytes(session_payload) + b"\n")
    session_path.chmod(0o600)
    producer_path = tmp_path / "producer.py"
    producer_path.write_bytes(b"#!/usr/bin/env python3\n")
    producer_path.chmod(0o700)
    stdout = b"Resolved 91 packages\n"
    stderr = b""
    framed = struct.pack(">Q", len(stdout)) + stdout + struct.pack(">Q", len(stderr)) + stderr
    source = _source()
    toolchain = _toolchain()
    protected = subject._sample_protected_roots()
    command = {
        "ordinal": 1,
        "argv": [
            subject.UV_PATH,
            "sync",
            "--python",
            subject.BASE_PYTHON_PATH,
            "--locked",
            "--all-extras",
            "--offline",
        ],
        "cwd": str(ROOT),
        "environment": _native_environment(work, target_venv),
        "exit_code": 0,
        "signal": None,
        "tool_version": subject.UV_VERSION_OUTPUT,
        "stdout_offset_bytes": 8,
        "stdout_size_bytes": len(stdout),
        "stdout_sha256": hashlib.sha256(stdout).hexdigest(),
        "stderr_offset_bytes": 8 + len(stdout) + 8,
        "stderr_size_bytes": len(stderr),
        "stderr_sha256": hashlib.sha256(stderr).hexdigest(),
    }
    session_binding = _bound_file(session_path, semantic_sha256=SHA)
    session_binding["session_id"] = "s1"
    receipt: dict[str, Any] = {
        "version": subject.COMMAND_RECEIPT_VERSION,
        "protocol_version": subject.PROTOCOL_VERSION,
        "session_binding": session_binding,
        "step": {
            "ordinal": 1,
            "role": "native_sync_log",
            "kind": "log",
            "filename": "10_native_sync.log",
        },
        "producer": {
            **_bound_file(producer_path),
            "version": "myquant.v17.v2.phase0-session-runner.v1",
        },
        "source_before": copy.deepcopy(source),
        "source_after": copy.deepcopy(source),
        "toolchain_before": copy.deepcopy(toolchain),
        "toolchain_after": copy.deepcopy(toolchain),
        "package_source_superset_before": {"row_count": 1, "sha256": SHA},
        "package_source_superset_after": {"row_count": 1, "sha256": SHA},
        "protected_roots_before": copy.deepcopy(protected),
        "protected_roots_after": copy.deepcopy(protected),
        "limitations": list(subject.NORMATIVE_LIMITATIONS),
        "outcome": "PASSED",
        "failure_codes": [],
        "commands": [command],
        "claims": {"exit_code": 0},
        "framing": subject.COMMAND_FRAMING,
        "output_sha256": hashlib.sha256(framed).hexdigest(),
        "output_size_bytes": len(framed),
    }
    if mutate is not None:
        mutate(receipt)
    receipt["semantic_sha256"] = hashlib.sha256(subject._canonical_bytes(receipt)).hexdigest()
    if mutate_framed is not None:
        framed = mutate_framed(framed)
    log_path = bundle / "10_native_sync.log"
    log_path.write_bytes(
        subject.COMMAND_RECEIPT_PREFIX + subject._canonical_bytes(receipt) + b"\n" + framed
    )
    log_path.chmod(0o600)
    return {
        "path": log_path,
        "work": work,
        "target_venv": target_venv,
        "source": source,
        "toolchain": toolchain,
        "protected": protected,
        "receipt": receipt,
    }


