def test_private_json_detects_parent_swap_and_retains_evidence(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    parent = tmp_path / "bundle"
    parent.mkdir(mode=0o700)
    moved = tmp_path / "bundle-moved"
    output = parent / "evidence.json"
    real_link = os.link
    swapped = False

    def swapping_link(*args: Any, **kwargs: Any) -> None:
        nonlocal swapped
        if not swapped:
            parent.rename(moved)
            parent.mkdir(mode=0o700)
            swapped = True
        real_link(*args, **kwargs)

    monkeypatch.setattr(subject.os, "link", swapping_link)
    with pytest.raises(subject.EvidenceError, match="parent path changed"):
        subject._write_private_json(output, {"a": 1})
    assert not output.exists()
    assert (moved / "evidence.json").exists()
    assert list(moved.glob(".evidence.json.*.tmp"))


def test_source_state_disables_textconv_and_binds_untracked_bytes(
    tmp_path: Path,
) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(("git", "init", "-q"), cwd=repo, check=True)
    subprocess.run(("git", "config", "user.email", "test@example.invalid"), cwd=repo, check=True)
    subprocess.run(("git", "config", "user.name", "Test"), cwd=repo, check=True)
    tracked = repo / "tracked.txt"
    tracked.write_text("base\n", encoding="utf-8")
    subprocess.run(("git", "add", "tracked.txt"), cwd=repo, check=True)
    subprocess.run(("git", "commit", "-qm", "base"), cwd=repo, check=True)
