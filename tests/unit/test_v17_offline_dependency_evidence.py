def _rehash(report: dict[str, Any]) -> None:
    report.pop("semantic_sha256", None)
    report["semantic_sha256"] = hashlib.sha256(subject._canonical_bytes(report)).hexdigest()


def test_schema_is_closed_draft_2020_12_and_validates_exact_v2(
    tmp_path: Path,
) -> None:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    preflight_packaged_schema(schema)
    report = _valid_report(tmp_path)
    validate_instance_against_schema(report, schema)
    subject._validate_evidence_v2(report)
    downgraded = copy.deepcopy(report)
    downgraded["schema_version"] = "v17_third_party_dependency_environment_evidence.v1"
    _rehash(downgraded)
    with pytest.raises(SchemaValidationError):
        validate_instance_against_schema(downgraded, schema)
    with pytest.raises(subject.EvidenceError, match="downgrade"):
        subject._validate_evidence_v2(downgraded)


